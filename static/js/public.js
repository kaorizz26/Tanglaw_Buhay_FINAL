    const fourpsTabs = Array.from(document.querySelectorAll("[data-fourps-tab]"));

    function updateFourpsTab(hash) {
        if (!fourpsTabs.length) {
            return;
        }

        const requestedSection = String(hash || "").replace(/^#/, "");
        const hasRequestedSection = fourpsTabs.some(function (link) {
            return link.dataset.fourpsTab === requestedSection;
        });
        const activeSection = hasRequestedSection
            ? requestedSection
            : fourpsTabs[0].dataset.fourpsTab;

        fourpsTabs.forEach(function (link) {
            const isActive = link.dataset.fourpsTab === activeSection;
            link.classList.toggle("is-active", isActive);
            if (isActive) {
                link.setAttribute("aria-current", "location");
            } else {
                link.removeAttribute("aria-current");
            }
        });
    }

    fourpsTabs.forEach(function (link) {
        link.addEventListener("click", function () {
            updateFourpsTab(link.hash);
        });
    });

    window.addEventListener("hashchange", function () {
        updateFourpsTab(window.location.hash);
    });

    updateFourpsTab(window.location.hash);
