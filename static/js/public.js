    const languageButtons = Array.from(document.querySelectorAll("[data-lang-option]"));

    function storedLanguage() {
        try {
            const selected = window.localStorage.getItem("tanglawPublicLanguage");
            return selected === "en" ? "en" : "fil";
        } catch (_error) {
            return "fil";
        }
    }

    function rememberLanguage(language) {
        try {
            window.localStorage.setItem("tanglawPublicLanguage", language);
        } catch (_error) {
            // The switch still works for the current page when storage is unavailable.
        }
    }

    function applyLanguage(language, saveChoice) {
        const activeLanguage = language === "en" ? "en" : "fil";
        const dictionary = translations[activeLanguage];

        document.documentElement.lang = activeLanguage;
        document.querySelectorAll("[data-i18n]").forEach(function (element) {
            const translation = dictionary[element.dataset.i18n];
            if (typeof translation === "string") {
                element.textContent = translation;
            }
        });

        document.querySelectorAll("[data-i18n-aria-label]").forEach(function (element) {
            const translation = dictionary[element.dataset.i18nAriaLabel];
            if (typeof translation === "string") {
                element.setAttribute("aria-label", translation);
            }
        });

        languageButtons.forEach(function (button) {
            const isActive = button.dataset.langOption === activeLanguage;
            button.classList.toggle("is-active", isActive);
            button.setAttribute("aria-pressed", String(isActive));
        });

        if (saveChoice) {
            rememberLanguage(activeLanguage);
        }
    }

    languageButtons.forEach(function (button) {
        button.addEventListener("click", function () {
            applyLanguage(button.dataset.langOption, true);
        });
    });

    applyLanguage(storedLanguage(), false);

    document.querySelectorAll("[data-statistics-sections]").forEach(function (container) {
        const tabs = Array.from(container.querySelectorAll("[data-statistics-section-tab]"));
        const panels = Array.from(container.querySelectorAll("[data-statistics-section-panel]"));

        function showSection(section, focusTab) {
            const selectedTab = tabs.find(function (tab) {
                return tab.dataset.statisticsSectionTab === section;
            });

            if (!selectedTab) {
                return;
            }

            tabs.forEach(function (tab) {
                const isSelected = tab === selectedTab;
                tab.setAttribute("aria-selected", String(isSelected));
                tab.setAttribute("tabindex", isSelected ? "0" : "-1");
            });

            panels.forEach(function (panel) {
                panel.hidden = panel.dataset.statisticsSectionPanel !== section;
            });

            if (focusTab) {
                selectedTab.focus();
            }
        }

        tabs.forEach(function (tab, index) {
            tab.addEventListener("click", function () {
                showSection(tab.dataset.statisticsSectionTab, false);
            });

            tab.addEventListener("keydown", function (event) {
                let nextIndex;

                if (event.key === "ArrowRight") {
                    nextIndex = (index + 1) % tabs.length;
                } else if (event.key === "ArrowLeft") {
                    nextIndex = (index - 1 + tabs.length) % tabs.length;
                } else if (event.key === "Home") {
                    nextIndex = 0;
                } else if (event.key === "End") {
                    nextIndex = tabs.length - 1;
                } else {
                    return;
                }

                event.preventDefault();
                showSection(tabs[nextIndex].dataset.statisticsSectionTab, true);
            });
        });

        showSection("overview", false);
    });

